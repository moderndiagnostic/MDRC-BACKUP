            <p class="text-left mb-3">Patient is required to be full bladder i.e. urinary bladder should be full.</p>

            <h2 class="font-lg text-left mt-3 mb-2">Contrast administration</h2>
            <p class="text-left mb-3">Though in most of the examinations, contrast is not used. But some examinations will require administration of contrast. This is generally so when we suspect infective/inflammatory pathology or mass lesion. Sometimes contrast is administered for vascular studies and other special applications. Reports for kidney function such as blood urea, serum creatinine or any other investigation that may have been done for kidneys should be brought with the patient at the time of examination. Any history of allergy to drugs, diabetes and drugs that are being taken for treatment should be available.</p>
