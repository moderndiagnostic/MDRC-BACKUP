        <!-- Ultrasound start -->
        <div class="about-tab why-us px-3 mt-3 mb-3">
            <div class="why-img">
                <img src="assets/images/mdrc/imaging-test-info/ultrasound.jpg" class="img-fluid w-100 mb-3" alt="Why Us">
            </div>
            <h2 class="font-lg text-left mb-2">Ultrasound</h2>
            <p class="text-left mb-3">When to come empty stomach? All ultrasound examinations of upper abdomen or whole abdomen require you to come empty stomach. This is essentially to see gall bladder in distended condition. However, practically we are able to see it well in most of the patients and as a rule, we do not recommend empty stomach. But once in a while, if gall bladder is completely contracted, we may suggest you to come empty stomach again to have a better look at gall bladder.</p>
            <h2 class="font-lg text-left mt-3 mb-2">When to come full bladder?</h2>
            <p class="text-left mb-3">Generally all lower abdomen and whole abdomen examinations require full urinary bladder. Also, examinations of KUB and early pregnancy (generally up to 3-4 months) will require full bladder. Full bladder means you have to take lot of water at least 1-2 hrs before examination and not pass urine. A well distended urinary bladder helps in seeing uterus, ovaries and adnexa properly in females and prostate in males. It also helps in seeing small stones in bladder and ureters in KUB examination.</p>
            <p class="text-left mb-3">It is important to note that an urge to pass urine does not indicate you are having full bladder. This may be due to infection or enlargement of prostate.</p>
            <p class="text-left mb-3">A really full bladder will make you uncomfortable. We need you to have full bladder, but you should be comfortable. For these examinations, come with some margin to wait as your turn may not come immediately on reaching clinic.</p>
            <h2 class="font-lg text-left mt-3 mb-2">Examination of children</h2>
            <p class="text-left mb-3">Examination of small children is difficult if they are crying. A well satisfied child is less prone to crying. We do not normally recommend children to be be empty stomach except in some situations where it can be necessary for investigation. Sometimes child may need to be sedated.</p>
            <p class="text-left mb-3">When you come in for your ultrasound examination for pregnancy?</p>
            <p class="text-left mb-3">Drink 2 to 3 glasses of fruit juice/Water 20-30 minutes prior to the appointment unless otherwise ordered by your physician. We would also like some fluids in your bladder to bring the baby's head out of the pelvis, but it does not need to be extremely full.</p>
        </div>

        <!-- CT Scan Examination start -->
        <div class="about-tab bg-theme why-us p-3 mt-3 mb-3">
            <div class="why-img">
                <img src="assets/images/mdrc/imaging-test-info/ct-scan.jpg" class="img-fluid w-100 mb-3" alt="Why Us">
            </div>
            <h2 class="font-lg text-white text-left mb-2">CT Scan Examination</h2>
            <p class="text-left text-white mb-3">Most of the examination will require administration of contrast. This is generally so when we suspect infective/inflammatory pathology or mass lesion. Contrast is also administered for vascular studies and other special applications. Reports for kidney function such as blood urea, serum creatinine or any other investigation that may have been done for kidneys should be brought with the patient at the time of examination. Any history of diabetes and drugs that are being taken should also be available.</p>
            <h2 class="font-lg text-left text-white mt-3 mb-2">CT Coronary Angiography</h2>
            <h4 class="text-white mt-3 mb-2">Contrast Administration</h4>
            <p class="text-left text-white mb-3">Most of the examination will require administration of contrast. This is generally so when we suspect infective/inflammatory pathology or mass lesion. Contrast is also administered for vascular studies and other special applications. Reports for kidney function such as blood urea, serum creatinine or any other investigation that may have been done for kidneys should be brought with the patient at the time of examination. Any history of diabetes and drugs that are being taken should also be available.</p>
            <h2 class="font-lg text-left text-white mt-3 mb-2">CT Coronary Angiography</h2>
            <p class="text-left text-white mb-3">It is preferable to be fasting three hours prior to the test. You can take water one or two glasses of water, one hour prior to investigation. Please bring all your relevant medical records such as any procedure done, creatinine level, sugar level and details of drugs being used. After the procedure, we advise you to again take 3-4 glasses of water in the next 2 hours.</p>
            
            <h2 class="font-lg text-left text-white mt-3 mb-2">Upper abdomen and whole abdomen examinations</h2>
            <p class="text-left text-white mb-3">It is essential to come with overnight fasting for these examinations. Investigations will take 2-3 hrs or even more to complete as generally oral contrast is given and it takes time to reach Colon. We normally do not ask patient to come with full bladder as it will generally fill during the course of administration of oral contrast. However, you are required not to pass urine during this examination. For KUB and lower abdomen examinations There is no need of fasting for these examinations but full bladder is a requirement.</p>
            <p class="text-left text-white mb-3">Further, avoid examination immediately after taking food. A gap of 2 hrs is advisable whenever contrast is to be administered.</p>
            
            <h2 class="font-lg text-left text-white mt-3 mb-2">Head examinations</h2>
            <p class="text-left text-white mb-3">Normally no preparation is required for these examinations. But in case of children and those with neurological problems, patient may need to be sedated/anaesthetized as proper investigation can not be done, if the patient is moving his/her head.</p>
            
            <h2 class="font-lg text-left text-white mt-3 mb-2">Allergy to drugs and contrast media</h2>
            <p class="text-left text-white mb-3">Though we use non-ionic contrast media which has very few reactions, however, a severe reaction is a possibility. If you are allergic to any drug or contrast media, you must tell us before the test is conducted. This may require modification and different planning for examination.</p>
            <p class="text-left text-white mb-3">Your Creatinine levels should be known.</p>
            <p class="text-left text-white">If you are diabetic, then the history of the drugs you are taking should be known.</p>
        </div>

