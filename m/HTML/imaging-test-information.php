        <!-- X-Ray Examination start -->
        <div class="about-tab bg-grey rounded-0 why-us p-3 mt-3 mb-3">
            <div class="why-img">
                <img src="assets/images/mdrc/imaging-test-info/x-ray.jpg" class="img-fluid w-100 mb-3" alt="Why Us">
            </div>
            <h2 class="font-lg text-left mb-2">X-Ray Examination</h2>
            <p class="text-left mb-3">Generally no preparation is required for routine x-ray examinations. But x-ray of abdomen/ KUB/ LS spine will require you to have preparation from the night before the appointment with charcol/unienzyme and some laxatives. Special X-ray investigations will require additional preparations and these will be given to you at the time of appointment itself.</p>

            <h2 class="font-lg text-left mt-3 mb-2">Bone Densitometry & PFT</h2>
            <p class="text-left mb-3">Does not require any preparations.</p>

            <h2 class="font-lg text-left mt-3 mb-2">TMT, Echo & Stress Echo</h2>
            <p class="text-left mb-3">Do not come for these investigations immediately after taking meals. Please bring your previous ECG, X-ray Chest and any other investigation that you got done earlier. It is important for your study.</p>
            <p class="text-left mb-3">Small Children will be required to be sedated for Echocardiography.</p>

            <h2 class="font-lg text-left mt-3 mb-2">Pregnant Women</h2>
            <p class="text-left mb-3">Pregnant women are advised not to get an X-ray based investigations like X-ray, OPG Scan, CT Scan, Mammography etc. However, in some circumstances, if clinician requires the investigation, kindly inform the radiologist at the Centre about your status.</p>
            <p class="text-left mb-3">As per the new Govt guidelines, patient who wish to undergo a pregnancy Ultrasound must furnish a photo Identity such as Aadhar Card, Driving License, PAN card, Ration Card, Passport etc **. Original prescription of qualified doctor for the examination is also must. You will also be required to fill a form and sign it.</p>

            <h2 class="font-lg text-left mt-3 mb-2">Neurology</h2>
            <p class="text-left mb-3">For EEG investigation patient should come with clean scalp. Head should not be greasy and there should be no oil in hair prior to investigation.</p>
            <p class="text-left text-red mb-3">** Failure to produce the above mentioned documents may result in denial of the test.**</p>
